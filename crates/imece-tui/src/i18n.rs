//! The screen's words in English (default) and Turkish. Templates use `{}`
//! for their arguments; `fill` cleans every argument, because arguments carry
//! text that agents wrote.

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Lang {
    En,
    Tr,
}

impl Lang {
    pub fn parse(s: &str) -> Option<Lang> {
        match s.trim().to_ascii_lowercase().as_str() {
            "en" | "english" => Some(Lang::En),
            "tr" | "turkish" | "türkçe" => Some(Lang::Tr),
            _ => None,
        }
    }

    pub fn other(self) -> Lang {
        match self {
            Lang::En => Lang::Tr,
            Lang::Tr => Lang::En,
        }
    }

    pub fn text(self) -> &'static Text {
        match self {
            Lang::En => &EN,
            Lang::Tr => &TR,
        }
    }
}

/// Removes control characters (an agent's text must not drive the terminal)
/// and hides words that look like secrets (see [`secret`]). A control
/// character becomes a space and parts words like one, so a tab or a
/// line break never glues a secret to the word before it.
pub fn clean(s: &str) -> String {
    let s: String = s
        .chars()
        .map(|c| if c.is_control() { ' ' } else { c })
        .collect();
    let mut out = String::with_capacity(s.len());
    // The word after `Bearer` or `Basic` is a credential whatever it is.
    let mut after_scheme = false;
    for (i, word) in s.split(' ').enumerate() {
        if i > 0 {
            out.push(' ');
        }
        let hide = secret(word) || (after_scheme && !word.is_empty());
        if !word.is_empty() {
            after_scheme = AUTH_SCHEMES.contains(&core(word));
        }
        out.push_str(if hide { "[***]" } else { word });
    }
    out
}

/// HTTP authorization schemes whose next word is a credential.
const AUTH_SCHEMES: &[&str] = &["Bearer", "Basic", "bearer", "basic"];

/// A name's word (see [`name_words`]) that ends with one of these makes
/// `NAME=value` or `NAME:value` a secret: `db_passwd`, `accessToken`,
/// `GOOGLE_CREDENTIALS`. `TOKENS` is none (`max_tokens=1000`).
const SECRET_WORDS: &[&str] = &[
    "TOKEN",
    "SECRET",
    "PASSWORD",
    "PASSWD",
    "PASSPHRASE",
    "CREDENTIAL",
    "CREDENTIALS",
];

/// `KEY` alone is code's word (`sort(key=len)`, `dict(key=1)`,
